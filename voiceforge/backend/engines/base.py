from abc import ABC, abstractmethod

class VoiceEngine(ABC):
    @abstractmethod
    def load(self, device='cpu'): ...
    @abstractmethod
    def unload(self): ...
    @abstractmethod
    def synthesize(self, text, voice_reference, emotion, seed, settings): ...
    @abstractmethod
    def get_capabilities(self): ...
    @abstractmethod
    def get_memory_usage(self): ...
